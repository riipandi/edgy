import { it } from '@effect/vitest'
import { Effect, Exit } from 'effect'
import { existsSync, readFileSync, symlinkSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { expect } from 'vite-plus/test'
import { failureOf, runCli, tempDirectory } from './cli.ts'

const output = (directory: string): string => join(directory, '.env.example')

it.effect('writes the example file into an empty directory', () =>
  Effect.gen(function* () {
    const directory = yield* tempDirectory
    const target = output(directory)

    const result = yield* runCli(['generate:config', '--output', target], {})

    expect(Exit.isSuccess(result.exit)).toBe(true)
    expect(result.output.join('\n')).toContain(`Wrote ${target}`)
    expect(readFileSync(target, 'utf8')).toContain('# Generated by')
  })
)

it.effect('writes the example file at --output', () =>
  Effect.gen(function* () {
    const directory = yield* tempDirectory
    const target = output(directory)

    const result = yield* runCli(['generate:config', '--output', target], {})

    expect(Exit.isSuccess(result.exit)).toBe(true)
    expect(result.output.join('\n')).toContain(`Wrote ${target}`)
    expect(readFileSync(target, 'utf8')).toContain('# Generated by')
  })
)

it.effect('refuses a real dotenv path', () =>
  Effect.gen(function* () {
    const directory = yield* tempDirectory
    const result = yield* runCli(['generate:config', '--output', join(directory, '.env')], {})

    expect(Exit.isFailure(result.exit)).toBe(true)
    expect(failureOf(result)).toContain('real dotenv files are never generated')
    expect(existsSync(join(directory, '.env'))).toBe(false)
  })
)

it.effect('refuses a symlink to a dotenv file, dangling or not', () =>
  Effect.gen(function* () {
    const directory = yield* tempDirectory
    const target = output(directory)
    symlinkSync('.env', target)

    const dangling = yield* runCli(['generate:config', '--output', target], {})
    expect(Exit.isFailure(dangling.exit)).toBe(true)
    expect(failureOf(dangling)).toContain('real dotenv files are never generated')
    expect(existsSync(join(directory, '.env'))).toBe(false)

    writeFileSync(join(directory, '.env'), 'KEEP=1\n')
    const live = yield* runCli(['generate:config', '--output', target], {})
    expect(Exit.isFailure(live.exit)).toBe(true)
    expect(readFileSync(join(directory, '.env'), 'utf8')).toBe('KEEP=1\n')
  })
)

it.effect('--check fails when the file is missing and passes when it is current', () =>
  Effect.gen(function* () {
    const directory = yield* tempDirectory
    const target = output(directory)

    const missing = yield* runCli(['generate:config', '--output', target, '--check'], {})
    expect(Exit.isFailure(missing.exit)).toBe(true)
    expect(failureOf(missing)).toContain('is missing')

    yield* runCli(['generate:config', '--output', target], {})
    const current = yield* runCli(['generate:config', '--output', target, '--check'], {})
    expect(Exit.isSuccess(current.exit)).toBe(true)
    expect(current.output.join('\n')).toContain('is up to date')
  })
)

it.effect('--check fails when the file is out of date', () =>
  Effect.gen(function* () {
    const directory = yield* tempDirectory
    const target = output(directory)
    yield* runCli(['generate:config', '--output', target], {})
    writeFileSync(target, `${readFileSync(target, 'utf8')}\nSTALE=1\n`)

    const result = yield* runCli(['generate:config', '--output', target, '--check'], {})

    expect(Exit.isFailure(result.exit)).toBe(true)
    expect(failureOf(result)).toContain('is out of date')
  })
)

it.effect('refuses to replace a differing file without --overwrite', () =>
  Effect.gen(function* () {
    const directory = yield* tempDirectory
    const target = output(directory)
    writeFileSync(target, 'CUSTOM=1\n')

    const result = yield* runCli(['generate:config', '--output', target], {})

    expect(Exit.isFailure(result.exit)).toBe(true)
    expect(failureOf(result)).toContain('pass --overwrite to replace it')
    expect(readFileSync(target, 'utf8')).toBe('CUSTOM=1\n')
  })
)

it.effect('--overwrite replaces a differing file once --force skips the prompt', () =>
  Effect.gen(function* () {
    const directory = yield* tempDirectory
    const target = output(directory)
    writeFileSync(target, 'CUSTOM=1\n')

    const refused = yield* runCli(['generate:config', '--output', target, '--overwrite'], {})
    expect(Exit.isFailure(refused.exit)).toBe(true)
    expect(failureOf(refused)).toContain('Refusing to overwrite non-interactively without --force')

    const written = yield* runCli(
      ['generate:config', '--output', target, '--overwrite', '--force'],
      {}
    )
    expect(Exit.isSuccess(written.exit)).toBe(true)
    expect(readFileSync(target, 'utf8')).toContain('# Generated by')
  })
)

it.effect('--force without --overwrite is a no-op, not an error', () =>
  Effect.gen(function* () {
    const directory = yield* tempDirectory
    const target = output(directory)

    const fresh = yield* runCli(['generate:config', '--output', target, '--force'], {})
    expect(Exit.isSuccess(fresh.exit)).toBe(true)
    expect(readFileSync(target, 'utf8')).toContain('# Generated by')

    const current = yield* runCli(['generate:config', '--output', target, '--force'], {})
    expect(Exit.isSuccess(current.exit)).toBe(true)
    expect(current.output.join('\n')).toContain('is already up to date')
  })
)

it.effect('rejects --stdout together with --check', () =>
  Effect.gen(function* () {
    const directory = yield* tempDirectory
    const target = output(directory)

    const result = yield* runCli(['generate:config', '--output', target, '--stdout', '--check'], {})

    expect(Exit.isFailure(result.exit)).toBe(true)
    expect(failureOf(result)).toContain('--stdout cannot be combined with --check')
  })
)

it.effect('--stdout prints the file and writes nothing', () =>
  Effect.gen(function* () {
    const directory = yield* tempDirectory
    const target = output(directory)

    const result = yield* runCli(['generate:config', '--output', target, '--stdout'], {})

    expect(Exit.isSuccess(result.exit)).toBe(true)
    expect(result.output.join('\n')).toContain('# Generated by')
    expect(existsSync(target)).toBe(false)
  })
)

it.effect('--help shows the documented default', () =>
  Effect.gen(function* () {
    const result = yield* runCli(['generate:config', '--help'])
    expect(result.output.join('\n')).toContain('(default: .env.example; never a real .env file)')
  })
)

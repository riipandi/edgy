import { build as esbuild, type BuildOptions, type Plugin } from 'esbuild'
import { rmSync } from 'node:fs'
import path from 'node:path'
import type { BuilderConfig } from './config.ts'
import { copyPath, writeText } from './copy.ts'
import { externalsPlugin, type ExternalPackage } from './externals.ts'
import { traceExternals } from './trace.ts'

/** Result of a successful build, used by the CLI and tests. */
export interface BuildResult {
  readonly outFile: string
  readonly serverDir: string
  readonly bytes: number
  readonly externals: readonly string[]
}

/** esbuild plugin that logs the resolution boundary between bundle and externals. */
const reportPlugin = (options: { readonly externals: Map<string, ExternalPackage> }): Plugin => ({
  name: 'builder:report',
  setup(build) {
    build.onEnd(() => {
      for (const pkg of options.externals.values()) {
        const label = pkg.reason === 'native' ? 'native' : 'configured'
        process.stdout.write(`  • external (${label}): ${pkg.name}\n`)
      }
    })
  }
})

/**
 * Builds the project into a self-contained server directory.
 *
 * Pipeline (the lean analogue of Nitro's rollup build):
 *
 * 1. Wipe and recreate `<outDir>/<serverDir>`.
 * 2. Bundle `entry` to a single ESM file. Native / configured packages are
 *    marked external by {@link externalsPlugin} and left as bare imports.
 * 3. Copy every traced external into `<serverDir>/node_modules`.
 * 4. Copy declared assets (e.g. a `migrations/` folder) into the output.
 * 5. Emit a `package.json` so the directory is a valid, runnable Node project.
 */
export const runBuild = async (config: BuilderConfig): Promise<BuildResult> => {
  const outFile = path.join(config.serverDir, config.entryFileName)
  const externals = new Map<string, ExternalPackage>()

  rmSync(config.serverDir, { recursive: true, force: true })

  const buildOptions: BuildOptions = {
    entryPoints: [path.resolve(config.rootDir, config.entry)],
    outfile: outFile,
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: config.target,
    minify: config.minify,
    sourcemap: config.sourcemap,
    metafile: true,
    logLevel: 'warning',
    // Bare specifiers left by the externals plugin must stay as-is.
    packages: 'bundle',
    plugins: [
      externalsPlugin({
        rootDir: config.rootDir,
        conditions: config.conditions,
        external: config.external,
        externals
      }),
      reportPlugin({ externals })
    ],
    // Preserve the `node:` prefix on builtins and keep ESM interop predictable.
    supported: { 'import-attributes': true },
    banner: {
      js: [
        '#!/usr/bin/env node',
        '// Generated by builder/ — do not edit. Run `pnpm build` to regenerate.'
      ].join('\n')
    }
  }

  const result = await esbuild(buildOptions)

  const traced = traceExternals({
    externals,
    serverDir: config.serverDir,
    conditions: config.conditions
  })

  for (const asset of config.assets) {
    copyPath(path.resolve(config.rootDir, asset.from), path.resolve(config.serverDir, asset.to))
  }

  writePackageJson(
    config,
    [...externals.values()].map((pkg) => pkg.name)
  )

  return {
    outFile,
    serverDir: config.serverDir,
    bytes: result.metafile ? entryBytes(result.metafile, config) : 0,
    externals: traced.packages
  }
}

/** Emits a minimal `package.json` so `node <serverDir>` works standalone. */
const writePackageJson = (config: BuilderConfig, externals: readonly string[]): void => {
  const manifest = {
    name: 'edgy-server',
    private: true,
    type: 'module',
    main: `./${config.entryFileName}`,
    dependencies: Object.fromEntries(externals.map((name) => [name, '*']))
  }
  writeText(path.join(config.serverDir, 'package.json'), `${JSON.stringify(manifest, null, 2)}\n`)
}

/** Sums the emitted output bytes from an esbuild metafile. */
const entryBytes = (
  metafile: { outputs: Record<string, { bytes: number }> },
  config: BuilderConfig
): number => {
  const relative = path.relative(config.rootDir, path.join(config.serverDir, config.entryFileName))
  return metafile.outputs[relative]?.bytes ?? 0
}
